#!/usr/bin/env node
/**
 * Builds the continent mask the hero globe draws its dots from.
 *
 *   node scripts/build-land-mask.js <path-to-node_modules>
 *
 * Takes N points spread evenly over a sphere (a Fibonacci lattice), tests each
 * one against real country outlines from Natural Earth (world-atlas, 1:50m),
 * and records land/sea as one bit per point. The browser regenerates the same
 * lattice and keeps the land points — so a whole dotted Earth ships as a few
 * kilobytes of bits instead of a texture or a coordinate list.
 *
 * Output: src/3d/land-mask.js
 */

const fs = require("fs");
const path = require("path");

const MODULES = process.argv[2];
if (!MODULES) throw new Error("usage: build-land-mask.js <node_modules dir>");

const topo = require(path.join(MODULES, "topojson-client"));
const world = require(path.join(MODULES, "world-atlas/land-50m.json"));

const N = 42000; // points on the sphere — keep in step with src/3d/globe.js
const land = topo.feature(world, world.objects.land);

/* Collect every polygon ring, with a bounding box for a cheap pre-check. */
const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  const list = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const rings of list) {
    let minX = 180, maxX = -180, minY = 90, maxY = -90;
    for (const [x, y] of rings[0]) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    polys.push({ rings, minX, maxX, minY, maxY });
  }
}

function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

function isLand(lon, lat) {
  for (const p of polys) {
    if (lon < p.minX || lon > p.maxX || lat < p.minY || lat > p.maxY) continue;
    if (!inRing(lon, lat, p.rings[0])) continue;
    let inHole = false;
    for (let h = 1; h < p.rings.length; h++) {
      if (inRing(lon, lat, p.rings[h])) {
        inHole = true;
        break;
      }
    }
    if (!inHole) return true;
  }
  return false;
}

/* Fibonacci lattice — must match fibonacciLatLon() in src/3d/globe.js exactly. */
const GOLDEN = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(N / 8));
let count = 0;
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((((GOLDEN * i) % (2 * Math.PI)) * 180) / Math.PI) - 180;
  if (isLand(lon, lat)) {
    bits[i >> 3] |= 1 << (i & 7);
    count++;
  }
}

const b64 = Buffer.from(bits).toString("base64");
const out = `/* Generated by scripts/build-land-mask.js — do not edit by hand.
   One bit per point of a ${N}-point Fibonacci sphere: 1 = land.
   Source: Natural Earth 1:50m land, via world-atlas. */
export const LAND_POINTS = ${N};
export const LAND_MASK = "${b64}";
`;

const target = path.resolve(__dirname, "../src/3d/land-mask.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out, "utf8");

console.log(
  "land mask: " + count + " land points of " + N + " (" + ((count / N) * 100).toFixed(1) + "%), " +
    b64.length + " bytes base64"
);
